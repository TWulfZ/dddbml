import { expect, it } from 'vitest';
import { generatePostgresSql } from './generatePostgresSql';

it('exports schema objects before composite and cyclic foreign keys', () => {
  const sql = generatePostgresSql(`
    Enum inventory.state {
      ready
      "it's done"
    }
    Table inventory.items {
      tenant_id int [not null]
      id bigint [increment]
      category_id int
      status inventory.state [default: 'ready']
      label text [default: 'it\\'s ready']
      indexes {
        (tenant_id, id) [pk]
        category_id [name: 'items_category_idx']
      }
      checks { \`tenant_id > 0\` [name: 'positive_tenant'] }
    }
    Table categories {
      id int [pk]
      featured_tenant int
      featured_item bigint
    }
    Ref category: inventory.items.category_id > categories.id [delete: set null, update: cascade]
    Ref featured: categories.(featured_tenant, featured_item) > inventory.items.(tenant_id, id)
    Ref diagram_only: inventory.items.tenant_id > categories.id [inactive]
    records categories (id) { 1 }
  `);

  expect(sql.indexOf('CREATE SCHEMA "inventory"')).toBeLessThan(sql.indexOf('CREATE TYPE'));
  expect(sql.indexOf('CREATE TYPE')).toBeLessThan(sql.indexOf('CREATE TABLE'));
  expect(sql.indexOf('CREATE TABLE "categories"')).toBeLessThan(sql.indexOf('ALTER TABLE'));
  expect(sql).toContain('PRIMARY KEY ("tenant_id", "id")');
  expect(sql).toContain('BIGINT GENERATED BY DEFAULT AS IDENTITY');
  expect(sql).toContain(`DEFAULT 'it''s ready'`);
  expect(sql).toContain(`'it''s done'`);
  expect(sql).toContain('CONSTRAINT "positive_tenant" CHECK (tenant_id > 0)');
  expect(sql).toContain('CREATE INDEX "items_category_idx" ON "inventory"."items"');
  expect(sql).toContain('FOREIGN KEY ("category_id") REFERENCES "categories" ("id") ON DELETE SET NULL ON UPDATE CASCADE');
  expect(sql).toContain('FOREIGN KEY ("featured_tenant", "featured_item") REFERENCES "inventory"."items" ("tenant_id", "id")');
  expect(sql).not.toMatch(/diagram_only|INSERT INTO/);
});

it('enforces one-to-one refs on their FK side and expands many-to-many refs into junction tables', () => {
  const sql = generatePostgresSql(`
    Table users { id int [pk] }
    Table profiles { user_id int [ref: - users.id] }
    Table teams { id int [pk] }
    Ref: users.id <> teams.id
  `);

  expect(sql).toContain('CREATE UNIQUE INDEX ON "profiles" ("user_id")');
  expect(sql).toContain('ALTER TABLE "profiles" ADD FOREIGN KEY ("user_id") REFERENCES "users" ("id")');
  expect(sql).toContain('CREATE TABLE "users_teams"');
  expect(sql).toContain('ALTER TABLE "users_teams" ADD FOREIGN KEY ("users_id") REFERENCES "users" ("id")');
  expect(sql).toContain('ALTER TABLE "users_teams" ADD FOREIGN KEY ("teams_id") REFERENCES "teams" ("id")');
});
